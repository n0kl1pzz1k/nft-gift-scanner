import os
import uuid

import psycopg
import pytest

from marketplace_offers_postgres import (
    install_postgres_offer_triggers,
    _verify_postgres_offer_triggers,
)


def test_postgres_offer_triggers_preserve_notifications_and_immutability():
    dsn = os.getenv("HASSLE_TEST_POSTGRES_DSN")
    if not dsn:
        pytest.skip("isolated PostgreSQL service is not configured")

    schema = "offer_triggers_" + uuid.uuid4().hex[:10]
    with psycopg.connect(dsn, autocommit=True) as pg:
        try:
            pg.execute(f'CREATE SCHEMA "{schema}"')
            pg.execute(f'SET search_path TO "{schema}"')
            pg.execute("""
                CREATE TABLE marketplace_orders (
                    id TEXT PRIMARY KEY, user_id TEXT NOT NULL, title TEXT NOT NULL,
                    owner_name TEXT NOT NULL, status TEXT NOT NULL, updated_at BIGINT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_offers (
                    id TEXT PRIMARY KEY, order_id TEXT NOT NULL, sender_user_id TEXT NOT NULL,
                    sender_name TEXT NOT NULL, status TEXT NOT NULL,
                    created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_notifications (
                    id TEXT PRIMARY KEY, user_id TEXT NOT NULL, event_type TEXT NOT NULL,
                    offer_id TEXT NOT NULL, order_id TEXT NOT NULL, order_title TEXT NOT NULL,
                    actor_name TEXT NOT NULL, created_at BIGINT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_deal_events (
                    id TEXT PRIMARY KEY, deal_id TEXT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_deal_lifecycle_events (
                    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id TEXT NOT NULL UNIQUE, deal_id TEXT NOT NULL
                )
            """)
            pg.execute("CREATE TABLE marketplace_payment_events (id TEXT PRIMARY KEY)")
            pg.execute("""
                CREATE TABLE marketplace_escrow_events (
                    id TEXT PRIMARY KEY, deal_id TEXT NOT NULL, actor_user_id TEXT NOT NULL,
                    event_type TEXT NOT NULL, event_key TEXT NOT NULL, event_data TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_dispute_resolution_approvals (
                    id TEXT PRIMARY KEY, deal_id TEXT NOT NULL, admin_user_id TEXT NOT NULL,
                    decision TEXT NOT NULL, idempotency_key TEXT NOT NULL, created_at BIGINT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_ledger_transactions (
                    id TEXT PRIMARY KEY, amount TEXT NOT NULL, currency TEXT NOT NULL
                )
            """)
            pg.execute("""
                CREATE TABLE marketplace_ledger_entries (
                    id TEXT PRIMARY KEY,
                    transaction_id TEXT NOT NULL REFERENCES marketplace_ledger_transactions(id),
                    direction TEXT NOT NULL, currency TEXT NOT NULL, amount TEXT NOT NULL
                )
            """)

            installed = install_postgres_offer_triggers(pg)
            assert installed["verified"] is True
            assert installed["triggers_installed"] == 26

            pg.execute(
                "INSERT INTO marketplace_orders VALUES (%s,%s,%s,%s,%s,%s)",
                ("order-1", "owner-1", "Rare gift", "Owner", "active", 100),
            )
            pg.execute(
                "INSERT INTO marketplace_offers VALUES (%s,%s,%s,%s,%s,%s,%s)",
                ("offer-1", "order-1", "buyer-1", "Buyer", "pending", 101, 101),
            )
            received = pg.execute(
                "SELECT user_id,event_type,order_title,actor_name FROM marketplace_notifications WHERE offer_id='offer-1'"
            ).fetchone()
            assert received == ("owner-1", "offer_received", "Rare gift", "Buyer")

            pg.execute(
                "INSERT INTO marketplace_offers VALUES (%s,%s,%s,%s,%s,%s,%s)",
                ("offer-2", "order-1", "buyer-2", "Buyer Two", "pending", 102, 102),
            )
            pg.execute(
                "UPDATE marketplace_orders SET status='cancelled',updated_at=103 WHERE id='order-1'"
            )
            status = pg.execute(
                "SELECT status FROM marketplace_offers WHERE id='offer-2'"
            ).fetchone()[0]
            assert status == "declined"
            declined = pg.execute(
                "SELECT user_id,event_type,actor_name FROM marketplace_notifications WHERE offer_id='offer-2' AND event_type='offer_declined'"
            ).fetchone()
            assert declined == ("buyer-2", "offer_declined", "Owner")

            pg.execute("INSERT INTO marketplace_deal_events VALUES ('event-1','deal-1')")
            with pytest.raises(psycopg.Error):
                pg.execute("UPDATE marketplace_deal_events SET deal_id='changed' WHERE id='event-1'")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_deal_events")
            pg.execute(
                "INSERT INTO marketplace_deal_lifecycle_events(id,deal_id) VALUES ('life-1','deal-1')"
            )
            with pytest.raises(psycopg.Error):
                pg.execute("DELETE FROM marketplace_deal_lifecycle_events WHERE id='life-1'")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_deal_lifecycle_events")

            pg.execute(
                "INSERT INTO marketplace_escrow_events VALUES (%s,%s,%s,%s,%s,%s,%s)",
                ("escrow-event-1", "deal-1", "buyer-1", "payment_pending", "deal-1:pending", "{}", 110),
            )
            with pytest.raises(psycopg.Error):
                pg.execute("UPDATE marketplace_escrow_events SET event_type='deal_completed' WHERE id='escrow-event-1'")
            with pytest.raises(psycopg.Error):
                pg.execute("DELETE FROM marketplace_escrow_events WHERE id='escrow-event-1'")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_escrow_events")
            pg.execute(
                "INSERT INTO marketplace_dispute_resolution_approvals VALUES (%s,%s,%s,%s,%s,%s)",
                ("approval-1", "deal-1", "admin-1", "refund_buyer", "approval-key-1", 111),
            )
            with pytest.raises(psycopg.Error):
                pg.execute("UPDATE marketplace_dispute_resolution_approvals SET decision='release_to_seller' WHERE id='approval-1'")
            with pytest.raises(psycopg.Error):
                pg.execute("DELETE FROM marketplace_dispute_resolution_approvals WHERE id='approval-1'")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_dispute_resolution_approvals")

            pg.execute("INSERT INTO marketplace_payment_events(id) VALUES (%s)", ("pay-event-1",))
            with pytest.raises(psycopg.Error):
                pg.execute("UPDATE marketplace_payment_events SET id='changed' WHERE id='pay-event-1'")
            with pytest.raises(psycopg.Error):
                pg.execute("DELETE FROM marketplace_payment_events WHERE id='pay-event-1'")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_payment_events")

            with pg.transaction():
                pg.execute(
                    "INSERT INTO marketplace_ledger_transactions(id,amount,currency) VALUES (%s,%s,%s)",
                    ("ledger-tx-1", "2.5", "TON"),
                )
                pg.execute(
                    "INSERT INTO marketplace_ledger_entries(id,transaction_id,direction,currency,amount) VALUES (%s,%s,%s,%s,%s)",
                    ("ledger-debit-1", "ledger-tx-1", "debit", "TON", "2.5"),
                )
                pg.execute(
                    "INSERT INTO marketplace_ledger_entries(id,transaction_id,direction,currency,amount) VALUES (%s,%s,%s,%s,%s)",
                    ("ledger-credit-1", "ledger-tx-1", "credit", "TON", "2.5"),
                )

            with pytest.raises(psycopg.Error):
                pg.execute("UPDATE marketplace_ledger_transactions SET amount='99' WHERE id='ledger-tx-1'")
            with pytest.raises(psycopg.Error):
                pg.execute("DELETE FROM marketplace_ledger_entries WHERE id='ledger-debit-1'")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_ledger_entries")
            with pytest.raises(psycopg.Error, match="immutable"):
                pg.execute("TRUNCATE TABLE marketplace_ledger_transactions CASCADE")

            with pytest.raises(psycopg.Error, match="ledger transaction must contain exactly one balanced debit and credit matching its amount"):
                with pg.transaction():
                    pg.execute(
                        "INSERT INTO marketplace_ledger_transactions(id,amount,currency) VALUES (%s,%s,%s)",
                        ("ledger-unbalanced", "2", "TON"),
                    )
                    pg.execute(
                        "INSERT INTO marketplace_ledger_entries(id,transaction_id,direction,currency,amount) VALUES (%s,%s,%s,%s,%s)",
                        ("ledger-only-debit", "ledger-unbalanced", "debit", "TON", "2"),
                    )

            # A successful DDL call is not proof that the final trigger set is intact.
            pg.execute("DROP TRIGGER trg_marketplace_offer_received ON marketplace_offers")
            with pytest.raises(RuntimeError, match="missing trigger trg_marketplace_offer_received"):
                _verify_postgres_offer_triggers(pg)
        finally:
            pg.execute("SET search_path TO public")
            pg.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')


def test_postgres_offer_schema_bootstrap_is_idempotent_and_creates_all_objects():
    dsn = os.getenv("HASSLE_TEST_POSTGRES_DSN")
    if not dsn:
        pytest.skip("isolated PostgreSQL service is not configured")

    from psycopg.rows import dict_row
    from marketplace_offers_postgres import initialize_postgres_offer_schema, verify_postgres_offer_schema

    schema = "offer_schema_" + uuid.uuid4().hex[:10]
    with psycopg.connect(dsn, autocommit=True, row_factory=dict_row) as pg:
        try:
            pg.execute(f'CREATE SCHEMA "{schema}"')
            pg.execute(f'SET search_path TO "{schema}"')
            pg.execute("""
                CREATE TABLE marketplace_orders (
                    id TEXT PRIMARY KEY, user_id TEXT NOT NULL, title TEXT NOT NULL,
                    owner_name TEXT NOT NULL, status TEXT NOT NULL, updated_at BIGINT NOT NULL
                )
            """)

            class Adapter:
                supports_for_update = True

                def execute(self, statement, parameters=()):
                    return pg.execute(statement, parameters)

            adapter = Adapter()
            first = initialize_postgres_offer_schema(adapter)
            second = initialize_postgres_offer_schema(adapter)
            assert first["verified"] is True
            assert second["verified"] is True
            assert first["verification"]["triggers_verified"] == 26
            assert first["verification"]["tables_verified"] == 11
            assert first["verification"]["columns_verified"] == 92
            assert first["verification"]["indexes_verified"] == 25

            tables = {
                row["table_name"]
                for row in pg.execute(
                    "SELECT table_name FROM information_schema.tables "
                    "WHERE table_schema = current_schema() AND table_type='BASE TABLE'"
                ).fetchall()
            }
            assert {
                "marketplace_orders", "marketplace_offers", "marketplace_deals",
                "marketplace_deal_events", "marketplace_deal_lifecycle_events",
                "marketplace_notifications", "marketplace_payment_intents",
                "marketplace_payment_events", "marketplace_ledger_transactions",
                "marketplace_ledger_entries", "marketplace_escrow_events", "marketplace_dispute_resolution_approvals",
            } <= tables

            indexes = {
                row["indexname"]
                for row in pg.execute(
                    "SELECT indexname FROM pg_indexes WHERE schemaname=current_schema()"
                ).fetchall()
            }
            assert "idx_marketplace_deals_one_open_reservation" in indexes

            # Simulate an installation whose escrow CHECK constraint predates
            # definitive Telegram Business transfer-rejection events.
            pg.execute("ALTER TABLE marketplace_escrow_events DROP CONSTRAINT marketplace_escrow_events_event_type_check")
            pg.execute("""
                ALTER TABLE marketplace_escrow_events
                ADD CONSTRAINT marketplace_escrow_events_event_type_check
                CHECK (event_type IN (
                    'deal_payment_requested', 'payment_intent_created', 'payment_pending',
                    'payment_confirmed', 'escrow_funded', 'asset_transfer_requested',
                    'asset_transfer_submitted', 'asset_transfer_confirmed', 'deal_completed',
                    'deal_disputed', 'refund_requested', 'refund_confirmed', 'payout_released',
                    'seller_credit_recorded', 'deal_cancelled', 'deal_expired',
                    'dispute_resolution_approved', 'dispute_resolution_ready'
                ))
            """)
            migrated = initialize_postgres_offer_schema(adapter)
            assert migrated["verified"] is True
            definition = pg.execute(
                """SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint
                   WHERE conrelid='marketplace_escrow_events'::regclass
                     AND conname='marketplace_escrow_events_event_type_check'"""
            ).fetchone()["definition"]
            assert "asset_transfer_rejected" in definition

            pg.execute("ALTER TABLE marketplace_offers DROP COLUMN sender_name")
            with pytest.raises(RuntimeError, match="missing columns in marketplace_offers: sender_name"):
                verify_postgres_offer_schema(Adapter())
        finally:
            pg.execute("SET search_path TO public")
            pg.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')


def test_postgres_offer_schema_bootstrap_rejects_legacy_permanent_order_unique_index():
    dsn = os.getenv("HASSLE_TEST_POSTGRES_DSN")
    if not dsn:
        pytest.skip("isolated PostgreSQL service is not configured")

    from psycopg.rows import dict_row
    from marketplace_offers_postgres import initialize_postgres_offer_schema

    schema = "offer_legacy_" + uuid.uuid4().hex[:10]
    with psycopg.connect(dsn, autocommit=True, row_factory=dict_row) as pg:
        try:
            pg.execute(f'CREATE SCHEMA "{schema}"')
            pg.execute(f'SET search_path TO "{schema}"')
            pg.execute("CREATE TABLE marketplace_orders (id TEXT PRIMARY KEY)")
            pg.execute("""
                CREATE TABLE marketplace_deals (
                    id TEXT PRIMARY KEY, order_id TEXT NOT NULL UNIQUE
                )
            """)

            class Adapter:
                supports_for_update = True

                def execute(self, statement, parameters=()):
                    return pg.execute(statement, parameters)

            with pytest.raises(RuntimeError, match="Legacy UNIQUE\\(order_id\\)"):
                initialize_postgres_offer_schema(Adapter())
        finally:
            pg.execute("SET search_path TO public")
            pg.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
