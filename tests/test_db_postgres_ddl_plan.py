def test_ddl_plan_renders_tables_checks_unique_indexes_and_foreign_keys():
    connection = sqlite3.connect(":memory:")
    connection.executescript(
        """
        CREATE TABLE parent (id TEXT PRIMARY KEY);
        CREATE TABLE child (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            parent_id TEXT NOT NULL,
            state TEXT NOT NULL CHECK(state IN ('open', 'closed')),
            code TEXT UNIQUE,
            FOREIGN KEY(parent_id) REFERENCES parent(id) ON DELETE CASCADE
        );
        CREATE INDEX idx_child_state ON child(state);
        """
    )
    result = build_postgres_ddl_plan(build_schema_manifest(connection))
    connection.close()

    rendered = "\n".join(result["statements"])
    assert 'CREATE TABLE "parent"' in rendered
    assert 'CREATE TABLE "child"' in rendered
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY" in rendered
    assert "CHECK (state IN ('open', 'closed'))" in rendered
    assert "UNIQUE (\"code\")" in rendered
    assert 'ALTER TABLE "child" ADD CONSTRAINT' in rendered
    assert "ON DELETE CASCADE" in rendered
    assert 'CREATE INDEX idx_child_state ON child(state)' in rendered
    assert result["execution_enabled"] is False
    assert result["ready_for_cutover"] is False


def test_ddl_plan_reports_defaults_triggers_and_views_as_blockers():
    connection = sqlite3.connect(":memory:")
    connection.executescript(
        """
        CREATE TABLE sample (id TEXT PRIMARY KEY, created TEXT DEFAULT CURRENT_TIMESTAMP);
        CREATE TRIGGER sample_guard BEFORE DELETE ON sample
        BEGIN SELECT RAISE(ABORT, 'no'); END;
        CREATE VIEW sample_view AS SELECT id FROM sample;
        """
    )
    result = build_postgres_ddl_plan(build_schema_manifest(connection))
    connection.close()

    features = {item["feature"] for item in result["blockers"]}
    assert "default on created" in features
    assert "trigger sample_guard" in features
    assert "view sample_view" in features
    assert result["blocker_count"] == len(result["blockers"])


def test_ddl_plan_handles_cyclic_foreign_keys_after_table_creation():
    connection = sqlite3.connect(":memory:")
    connection.executescript(
        """
        CREATE TABLE alpha (id TEXT PRIMARY KEY, beta_id TEXT,
            FOREIGN KEY(beta_id) REFERENCES beta(id));
        CREATE TABLE beta (id TEXT PRIMARY KEY, alpha_id TEXT,
            FOREIGN KEY(alpha_id) REFERENCES alpha(id));
        """
    )
    result = build_postgres_ddl_plan(build_schema_manifest(connection))
    connection.close()

    rendered = "\n".join(result["statements"])
    assert rendered.index('CREATE TABLE "alpha"') < rendered.index('ALTER TABLE "alpha"')
    assert result["deferred_foreign_key_count"] == 2



