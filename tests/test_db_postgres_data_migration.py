import sqlite3

from db_postgres_data_migration import _fingerprint, _normal, _ordered_select, _sqlite_autoincrement_high_water
from db_schema_audit import build_schema_manifest


def test_fingerprint_normalizes_sqlite_and_postgres_numeric_adapters():
    from decimal import Decimal
    assert _normal(1) == _normal(True)
    assert _normal(1.25) == _normal(Decimal("1.250"))
    assert _fingerprint([(1, "x"), (2, None)])[0] == 2


def test_ordered_select_uses_primary_key_order_and_quoted_identifiers():
    connection = sqlite3.connect(":memory:")
    connection.execute('CREATE TABLE "odd table" ("key id" TEXT PRIMARY KEY, value TEXT)')
    manifest = build_schema_manifest(connection)
    statement, columns = _ordered_select(connection, manifest["tables"][0])
    assert columns == ["key id", "value"]
    assert 'ORDER BY "key id"' in statement
    connection.close()


def test_ordered_select_falls_back_to_all_columns_without_primary_key():
    connection = sqlite3.connect(":memory:")
    connection.execute("CREATE TABLE no_key (a TEXT, b INTEGER)")
    manifest = build_schema_manifest(connection)
    statement, columns = _ordered_select(connection, manifest["tables"][0])
    assert 'ORDER BY "a", "b"' in statement
    connection.close()



def test_fingerprint_is_independent_of_row_order():
    rows = [(1, "alpha"), (2, "beta"), (3, None)]
    assert _fingerprint(rows) == _fingerprint(list(reversed(rows)))



def test_autoincrement_high_water_survives_deleted_highest_row():
    connection = sqlite3.connect(":memory:")
    connection.execute("CREATE TABLE items (id INTEGER PRIMARY KEY AUTOINCREMENT, value TEXT)")
    connection.execute("INSERT INTO items(value) VALUES ('first')")
    connection.execute("INSERT INTO items(value) VALUES ('second')")
    connection.execute("DELETE FROM items WHERE id = 2")
    assert _sqlite_autoincrement_high_water(connection, "items") == 2
    connection.close()



def test_transactional_copy_to_isolated_postgres_preserves_rows_and_sequence(tmp_path):
    import os
    import pytest
    import psycopg
    from db_postgres_data_migration import migrate
    from db_backup import backup_database

    dsn = os.getenv("HASSLE_TEST_POSTGRES_DSN")
    if not dsn:
        pytest.skip("isolated PostgreSQL service is not configured")

    source_path = tmp_path / "source.sqlite3"
    source = sqlite3.connect(source_path)
    source.execute("CREATE TABLE items (id INTEGER PRIMARY KEY AUTOINCREMENT, value TEXT NOT NULL)")
    source.execute("INSERT INTO items(value) VALUES ('one')")
    source.execute("INSERT INTO items(value) VALUES ('two')")
    source.execute("DELETE FROM items WHERE id = 2")
    source.commit()
    source.close()
    backup_path = tmp_path / "source.backup.sqlite3"
    backup_database(source_path, backup_path)

    with psycopg.connect(dsn) as target:
        target.execute("DROP TABLE IF EXISTS b_items, a_items, items CASCADE")
        target.execute("CREATE TABLE items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value TEXT NOT NULL)")

    report = migrate(str(backup_path), dsn, batch_size=1, execute=True)
    assert report["committed"] is True
    assert report["tables"][0]["content_verified"] is True
    assert report["tables"][0]["source_rows"] == 1

    with psycopg.connect(dsn) as target:
        rows = target.execute("SELECT id, value FROM items ORDER BY id").fetchall()
        next_id = target.execute("SELECT nextval(pg_get_serial_sequence('items', 'id'))").fetchone()[0]
        assert rows == [(1, "one")]
        assert next_id == 3



def test_postgres_copy_rolls_back_all_tables_when_later_table_fails(tmp_path):
    import os
    import psycopg
    import pytest
    from db_postgres_data_migration import migrate
    from db_backup import backup_database

    dsn = os.getenv("HASSLE_TEST_POSTGRES_DSN")
    if not dsn:
        pytest.skip("isolated PostgreSQL service is not configured")

    source_path = tmp_path / "rollback.sqlite3"
    source = sqlite3.connect(source_path)
    source.executescript(
        """
        CREATE TABLE a_items (id TEXT PRIMARY KEY, value TEXT NOT NULL);
        CREATE TABLE b_items (id TEXT PRIMARY KEY, value INTEGER NOT NULL);
        INSERT INTO a_items VALUES ('a1', 'valid');
        INSERT INTO b_items VALUES ('b1', 99);
        """
    )
    source.commit()
    source.close()
    backup_path = tmp_path / "rollback.backup.sqlite3"
    backup_database(source_path, backup_path)

    with psycopg.connect(dsn) as target:
        target.execute("DROP TABLE IF EXISTS b_items, a_items, items CASCADE")
        target.execute("CREATE TABLE a_items (id TEXT PRIMARY KEY, value TEXT NOT NULL)")
        target.execute("CREATE TABLE b_items (id TEXT PRIMARY KEY, value INTEGER NOT NULL CHECK (value < 10))")

    with pytest.raises(psycopg.Error):
        migrate(str(backup_path), dsn, batch_size=1, execute=True)

    with psycopg.connect(dsn) as target:
        assert target.execute("SELECT COUNT(*) FROM a_items").fetchone()[0] == 0
        assert target.execute("SELECT COUNT(*) FROM b_items").fetchone()[0] == 0



